/** Fecha ISO (YYYY-MM-DD) → "8 de agosto de 2026" (es-MX, sin zona horaria). */
export function formatDateEs(iso: string | null | undefined): string | null {
  if (!iso) return null;
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso.trim());
  if (!m) return null;
  const y = Number(m[1]);
  const mo = Number(m[2]);
  const d = Number(m[3]);
  if (!y || !mo || !d) return null;
  const months = [
    "enero",
    "febrero",
    "marzo",
    "abril",
    "mayo",
    "junio",
    "julio",
    "agosto",
    "septiembre",
    "octubre",
    "noviembre",
    "diciembre",
  ];
  const name = months[mo - 1];
  if (!name) return null;
  return `${d} de ${name} de ${y}`;
}
